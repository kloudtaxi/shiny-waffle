"""Step 7 graph checks on the luna scale KBs. Read-only SQL; writes graph-checks.md next to notes.md.

    python3 "runs/2026-10-13-utopia-aad5b06+c4da9cc-luna-scale-large/scripts/graph_checks.py"

1. Does the 15% clause survive extraction? Live facts evidenced by the agreement or the exception
   whose quote, phrase or value carries "15".
2. Is the bare "Acme" in `email_sarah_to_michael.md` attached to Acme Industrial Supply? Every
   live fact evidenced by the email, with its subject and object.
3. Does the org chart yield reporting lines? Live facts evidenced by `organization_chart.md`
   whose phrase mentions reporting or management.
4. The S05 hearsay: live facts evidenced by `acme_account_strategy.md` that mention "believe",
   "Deal Desk", "preferential" or "15".
"""

from __future__ import annotations

import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
KBS = {"base": "01a136fa-8e1d-77c0-b01d-bfc6423990b4",
       "missing-contract": "01a136fa-a00d-7421-b90b-4ad99714585b"}  # fmt: skip


def sql(q: str) -> list[list[str]]:
    out = subprocess.run(["docker", "exec", "utopia-db-1", "psql", "-U", "utopia", "-d", "utopia",
                          "-A", "-F", "\t", "-P", "footer=off", "-t", "-c", q],
                         check=True, capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines() if line]


def facts(kb: str, filename: str, where: str = "true") -> list[list[str]]:
    """Live facts evidenced by one document: subject, phrase, object or value, confidence, quote."""
    return sql(f"""
        select distinct s.canonical_name, coalesce(f.phrase, ''),
               coalesce(o.canonical_name, f.object_value->>'value', f.object_value::text, ''),
               round(f.confidence::numeric, 2)::text, f.layer,
               left(regexp_replace(coalesce(fe.quote, ''), '\\s+', ' ', 'g'), 160)
          from facts f
          join fact_evidence fe on fe.fact_id = f.id
          join documents d on d.id = fe.document_id
          join entities s on s.id = f.subject_id
          left join entities o on o.id = f.object_id
         where f.kb_id = '{kb}' and f.invalidated_at is null and d.deleted_at is null
           and d.filename = '{filename}' and ({where})
         order by 1, 2, 3""")


def table(rows: list[list[str]]) -> str:
    if not rows:
        return "_none_\n"
    head = "| subject | phrase | object / value | conf | layer | quote |\n|---|---|---|---|---|---|\n"
    esc = lambda c: c.replace("|", "\\|")  # noqa: E731
    return head + "".join("| " + " | ".join(esc(c) for c in r) + " |\n" for r in rows)


def main() -> None:
    fifteen = ("fe.quote ilike '%15%' or f.phrase ilike '%15%' "
               "or coalesce(f.object_value::text, '') ilike '%15%' or o.canonical_name ilike '%15%'")
    reporting = ("f.phrase ilike '%report%' or f.phrase ilike '%manag%' "
                 "or f.phrase ilike '%supervis%' or f.phrase ilike '%lead%'")
    hearsay = ("fe.quote ilike '%believe%' or fe.quote ilike '%deal desk%' "
               "or fe.quote ilike '%preferential%' or f.phrase ilike '%confirm%' "
               "or coalesce(o.canonical_name, '') ilike '%deal desk%' or " + fifteen)
    out = ["# Graph checks (step 7), luna scale KBs\n",
           "Generated by `scripts/graph_checks.py` (read-only SQL). Live facts only; one row per "
           "distinct fact and quote.\n"]
    for name, kb in KBS.items():
        out.append(f"\n## {name} (`{kb}`)\n")
        n_org = sql(f"select count(distinct f.id) from facts f join fact_evidence fe on fe.fact_id=f.id "
                    f"join documents d on d.id=fe.document_id where f.kb_id='{kb}' and f.invalidated_at "
                    f"is null and d.filename='organization_chart.md'")[0][0]
        for title, filename, where in (
            ("1. The 15% clause: `acme_master_supply_agreement.md`", "acme_master_supply_agreement.md", fifteen),
            ("1. The 15% clause: `acme_pricing_exception.md`", "acme_pricing_exception.md", fifteen),
            ("2. Every fact from `email_sarah_to_michael.md`", "email_sarah_to_michael.md", "true"),
            (f"3. Reporting lines from `organization_chart.md` ({n_org} live facts in all)",
             "organization_chart.md", reporting),
            ("4. Hearsay in `acme_account_strategy.md`", "acme_account_strategy.md", hearsay),
        ):
            rows = facts(kb, filename, where)
            out.append(f"\n### {title}: {len(rows)} row(s)\n\n{table(rows)}")
    (HERE.parent / "graph-checks.md").write_text("".join(out))
    print("wrote", HERE.parent / "graph-checks.md")


if __name__ == "__main__":
    main()
